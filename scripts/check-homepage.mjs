import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { PLAY_URL, COMMUNITY_URL } from '../src/lib/links.mjs';
import { GAMES, SPOTLIGHT_ID, gridGames, EXTRAS, COMING_SOON } from '../src/lib/games.mjs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const out=process.env.HOMEPAGE_SCREENSHOT_DIR || join(tmpdir(),'nopas-homepage-review');
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4321/',{waitUntil:'networkidle'});
await page.evaluate(()=>document.fonts.ready);
assert.equal(await page.locator("video").count(),0, "Rejected local development clip must not be promoted");
await page.evaluate(()=>scrollTo(0,0)); await page.screenshot({path:out+'/homepage-desktop.png',fullPage:true,style:'astro-dev-toolbar { display:none!important }'}); await page.screenshot({path:out+'/homepage-desktop-hero.png',style:'astro-dev-toolbar { display:none!important }'});
// The newest game is the spotlight; every other game is a card. Read from the games list, never a hard-coded count.
const spotlight=GAMES.find(g=>g.id===SPOTLIGHT_ID);
assert.equal(await page.locator('.game-spotlight').count(),1,'one spotlight');
assert.equal(await page.locator('.game-spotlight').getAttribute('data-game-id'),SPOTLIGHT_ID);
assert.equal(await page.locator('.game-spotlight .game-spotlight-play').getAttribute('href'),PLAY_URL);
assert.equal(await page.locator('.game-spotlight .game-spotlight-play').getAttribute('target'),'_blank');
assert.equal(await page.locator('.game-spotlight .game-spotlight-more').getAttribute('href'),spotlight.href);
const cards=await page.locator('#games .game-card').evaluateAll(es=>es.map(e=>({id:e.id,gameId:e.dataset.gameId,href:e.getAttribute('href'),width:e.clientWidth,height:e.clientHeight})));
console.log('desktop cards',cards,'overflow',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
assert.deepEqual(cards.map(c=>c.id),gridGames().map(g=>g.id),'card ids follow the games list');
assert.deepEqual(cards.map(c=>c.gameId),gridGames().map(g=>g.id));
assert.deepEqual(cards.map(c=>c.href),gridGames().map(g=>g.href),'each card links to its game');
assert.ok(cards.every(c=>c.width===cards[0].width && c.height===cards[0].height),'cards share one size');
for(const id of ['bowling','survivors','match']) assert.equal(await page.locator(`[id="${id}"]`).count(),1,`#${id} resolves to one element`);
const extras=await page.locator('.game-extras').innerText();
for(const x of EXTRAS) assert.ok(extras.includes(x.name),`extras name ${x.name}`);
assert.ok(extras.includes(COMING_SOON.line),'coming-soon line verbatim');
assert.match(await page.locator('main h1').innerText(),/One ridiculous universe\.\s*Every kind of chaos\./);
assert.equal(await page.locator('main h1').count(),1);
const countWords=/three (ways|modes|games)|all three/i;
assert.doesNotMatch(await page.title(),countWords,'title is count-free');
assert.doesNotMatch(await page.locator('meta[name="description"]').getAttribute('content'),countWords,'description is count-free');
assert.doesNotMatch(await page.locator('body').innerText(),countWords,'body copy is count-free');
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>scrollTo(0,0)); await page.screenshot({path:out+'/homepage-mobile.png',fullPage:true,style:'astro-dev-toolbar { display:none!important }'}); await page.screenshot({path:out+'/homepage-mobile-hero.png',style:'astro-dev-toolbar { display:none!important }'});
console.log('mobile overflow',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.getByRole('button',{name:'Open menu',exact:true}).click();
console.log('mobile menu',await page.locator('#mobile-menu-toggle').getAttribute('aria-expanded'));
assert.equal(await page.locator('#mobile-menu-toggle').getAttribute('aria-expanded'),'true');
assert.ok(await page.locator(`#mobile-menu a[href="${PLAY_URL}"]`).isVisible(),'Play link in the open mobile menu');
await page.getByRole('button',{name:'Close menu',exact:true}).click();
// Open beta is live: the hero leads with the Share Link, then the community. Not clicked — both leave the site.
const heroActions=await page.locator('.hero-actions a').evaluateAll(es=>es.map(a=>({href:a.getAttribute('href'),target:a.target,text:a.textContent.trim()})));
console.log('hero actions',heroActions);
assert.equal(heroActions.length,2);
assert.equal(heroActions[0].href,PLAY_URL);assert.equal(heroActions[0].target,'_blank');assert.match(heroActions[0].text,/Play/);
assert.equal(heroActions[1].href,COMMUNITY_URL);assert.equal(heroActions[1].target,'_blank');
assert.match(await page.locator('.availability').innerText(),/Live now/);
await page.locator('.hero-watch').click();
console.log('gameplay anchor',new URL(page.url()).hash);
assert.equal(new URL(page.url()).hash,'#gameplay');

await page.route('**/www.youtube-nocookie.com/**',r=>r.fulfill({body:'video embed verified'}));
await page.locator('.video-facade').first().click();
console.log('embed',await page.locator('iframe').getAttribute('src'));
assert.match(await page.locator('iframe').getAttribute('src'),/youtube-nocookie.com\/embed\/kSqdf0DlD8s/);
await page.emulateMedia({reducedMotion:'reduce'});await page.reload({waitUntil:'networkidle'});
assert.equal(await page.locator("iframe").count(),0);
for(const width of [320,768,1024]) {
 await page.setViewportSize({width,height:900});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`overflow at ${width}`);
}
await page.locator('#theme-toggle').click();
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
assert.deepEqual(errors,[]);
console.log('All homepage checks passed. Screenshots:',out);
await browser.close();
